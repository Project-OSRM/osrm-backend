#!/usr/bin/env bash

set -o errexit
set -o pipefail
set -o nounset

# Generates the flatbuffers JavaScript bundle the cucumber steps and node tests
# import, from include/engine/api/flatbuffers/*.fbs.
#
# The output is gitignored and built on demand: features/support/fbresult.js
# runs this script before loading the bundle, so it cannot drift from the
# schemas the way a committed copy could. The C++ headers get the same
# treatment from flatbuffers_generate_headers in CMakeLists.txt.
#
# The output lives outside the directories cucumber.mjs imports, so cucumber
# never loads it before this script has had a chance to refresh it.
#
# The bundle records a hash of its inputs (the schemas and this script). When
# the hash still matches, the script exits without touching flatc, so calling
# it at the start of every test run costs almost nothing.
#
# Usage: regenerate_fbresult_js.sh [--force]
#   FLATC            path to flatc (default: the one vcpkg installed into the
#                    build directory, then flatc on PATH)
#   OSRM_BUILD_DIR   build directory to search for flatc first

ROOT=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
cd "$ROOT"

SCHEMA_DIR=include/engine/api/flatbuffers
OUTPUT=features/generated/fbresult.js

FORCE=0
if [ "${1:-}" = "--force" ]; then
    FORCE=1
fi

sha256() {
    if command -v sha256sum > /dev/null 2>&1; then
        sha256sum | cut -d' ' -f1
    else
        shasum -a 256 | cut -d' ' -f1
    fi
}

# Sorted so the hash does not depend on glob order.
INPUT_HASH=$(
    for f in $(printf '%s\n' "$SCHEMA_DIR"/*.fbs | LC_ALL=C sort) scripts/regenerate_fbresult_js.sh; do
        echo "$f"
        cat "$f"
    done | sha256
)
HASH_LINE="// inputs-sha256: $INPUT_HASH"

if [ "$FORCE" = 0 ] && [ -f "$OUTPUT" ] && grep -qxF "$HASH_LINE" "$OUTPUT"; then
    exit 0
fi

# flatc ships with the vcpkg flatbuffers port, so any configured build has one.
if [ -z "${FLATC:-}" ]; then
    for dir in "${OSRM_BUILD_DIR:-}" build*; do
        [ -n "$dir" ] && [ -d "$dir" ] || continue
        FLATC=$(find "$dir" -path '*tools/flatbuffers/flatc' -type f 2>/dev/null | head -1)
        [ -n "$FLATC" ] && break
    done
fi
if [ -z "${FLATC:-}" ] && command -v flatc > /dev/null 2>&1; then
    FLATC=flatc
fi
if [ -z "${FLATC:-}" ]; then
    cat >&2 <<EOF
Cannot generate $OUTPUT: no flatc found.
The cucumber steps and node tests decode flatbuffers responses with a bundle
generated from $SCHEMA_DIR/*.fbs. To build it, either:
  - configure a build (vcpkg installs flatc into it), or
  - set FLATC=/path/to/flatc, or put flatc on PATH.
EOF
    exit 1
fi

echo "Generating $OUTPUT using $("$FLATC" --version)"

WORK=$(mktemp -d)
trap 'rm -rf "$WORK"' EXIT

# --gen-all matters here. Without it flatc emits only the types declared in the
# named schema, and it rewrites the namespace barrel once per schema, so passing
# every .fbs file leaves a barrel holding whichever one ran last. Passing just
# fbresult.fbs is enough because it includes route.fbs and table.fbs, which in
# turn include waypoint.fbs and position.fbs.
"$FLATC" --ts --gen-all -o "$WORK" -I "$SCHEMA_DIR" "$SCHEMA_DIR/fbresult.fbs"

# The step definitions import a single nested `osrm` object. flatc emits a flat
# namespace barrel instead, so wrap it.
cat > "$WORK/entry.ts" <<'ENTRY'
import * as fbresult from './osrm/engine/api/fbresult.js';
export const osrm = { engine: { api: { fbresult } } };
ENTRY

# flatbuffers is left external so the bundle uses the npm runtime dependency
# rather than inlining a second copy of it. esbuild writes the source path of
# each chunk as a comment, relative to its working directory, so run it from
# inside the work directory. Running it from the repository root would bake the
# absolute path of the temporary directory into the output and give a different
# result on every machine.
(cd "$WORK" && "$ROOT/node_modules/.bin/esbuild" entry.ts \
    --bundle \
    --format=esm \
    --external:flatbuffers \
    --log-level=warning \
    --outfile=bundle.js)

mkdir -p "$(dirname "$OUTPUT")"

# Write next to the destination and rename, so a parallel test worker that is
# checking the hash at the same moment never reads a half-written file.
TMP_OUTPUT=$(mktemp "$OUTPUT.XXXXXX")
{
    echo "// automatically generated by the FlatBuffers compiler, do not modify"
    echo "// Generated from TypeScript using flatc --ts and esbuild"
    echo "// Regenerate with: npm run regenerate-fbresult"
    echo "$HASH_LINE"
    echo ""
    cat "$WORK/bundle.js"
} > "$TMP_OUTPUT"
mv -f "$TMP_OUTPUT" "$OUTPUT"

echo "Wrote $OUTPUT"
